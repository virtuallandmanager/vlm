/**
 * Mirrors apps/ring-marker/tests/test_detect.py on the synthetic test set (generated by the Gradle
 * task ringTestset).
 */
class RingDetectorTest {
  private class Image(val gray: ByteArray, val width: Int, val height: Int)

  private class Entry(
      val name: String,
      val case: String,
      val expectNone: Boolean,
      val markers: List<JsonObject>,
      val image: Image,
  )

  private fun ids(found: List<RingDetection>) = found.map { "0x" + it.id.toString(16) }

  @Test
  fun testsetCases() {
    val failures = mutableListOf<String>()
    for (e in manifest) {
      val found = detections.getValue(e.name)
      if (e.expectNone) {
        if (found.isNotEmpty()) failures.add("${e.name}: expected none, got ${ids(found)}")
        continue
      }
      val want = e.markers.map { it["id"]!!.jsonPrimitive.long }.toSet()
      val got = found.map { it.id }.toSet()
      if (got != want || found.size != want.size) {
        failures.add("${e.name}: ids ${ids(found)}, want ${want.map { "0x" + it.toString(16) }}")
        continue
      }
      for (m in e.markers) {
        val d = found.single { it.id == m["id"]!!.jsonPrimitive.long }
        val c = m["center_px"]!!.jsonArray
        val err = hypot(d.cx - c[0].jsonPrimitive.double, d.cy - c[1].jsonPrimitive.double)
        if (err > 3) failures.add("${e.name}: centre error $err")
      }
    }
    assertTrue(failures.joinToString("\n"), failures.isEmpty())
  }

  @Test
  fun neverWrongId() {
    for (e in manifest) {
      val drawn = e.markers.map { it["id"]!!.jsonPrimitive.long }.toSet()
      for (d in detections.getValue(e.name)) {
        assertTrue("${e.name}: 0x${d.id.toString(16)}", d.id in drawn)
      }
    }
  }

  @Test
  fun rotationReported() {
    for ((name, want) in listOf("rotated_73" to 73.0, "rotated_180" to 180.0)) {
      val d = detections.getValue(name).single()
      val diff = ((d.rotationDeg - want + 180) % 360 + 360) % 360 - 180
      assertTrue("$name: ${d.rotationDeg}", kotlin.math.abs(diff) <= 2)
    }
  }

  @Test
  fun fastEnough() {
    val range = manifest.filter { it.case == "range" }
    assertEquals(27, range.size)
    val detector = RingDetector()
    repeat(5) { for (e in range) detector.detect(e.image.gray, e.image.width, e.image.height) }
    val times =
        range
            .map { e ->
              val t0 = System.nanoTime()
              detector.detect(e.image.gray, e.image.width, e.image.height)
              (System.nanoTime() - t0) / 1e6
            }
            .sorted()
    val median = times[times.size / 2]
    println("RingDetector median over ${times.size} range images: %.2f ms".format(median))
    assertTrue("median $median ms", median < 40.0)
  }

  /**
   * A marker partly out of frame decodes to its own id or not at all; cells sampled off the image
   * are erasures. Python crops a 300 px render; here the frontal 0.6 m RING140 view is cropped so
   * its centre ends 20-80 px from an edge (Python detects the same crops: left/right/bottom up to
   * 56 px, top never, since the gap is cut first).
   */
  @Test
  fun croppedMarkerErasesOffImageCells() {
    val src = manifest.single { it.name == "range-RING140-0.6-0" }
    val id = src.markers.single()["id"]!!.jsonPrimitive.long
    val ppm = testsetFocalPx / 600.0 // px per mm, frontal at 0.6 m
    val detector = RingDetector()
    var checked = 0
    var foundAny = 0
    for (cut in 560 until 620 step 6) {
      for (side in listOf("left", "right", "top", "bottom")) {
        val im = crop(src.image, side, cut)
        val found = detector.detect(im.gray, im.width, im.height)
        assertTrue("$side $cut: ${ids(found)}", found.all { it.id == id })
        if (found.isEmpty()) continue
        foundAny++
        val cx = 639.5 - (if (side == "left") cut else 0)
        // true centre in pixel-index coordinates after the crop
        val cy = 479.5 - (if (side == "top") cut - 160 else 0)
        val cells = detector.readCellsNear(im.gray, im.width, im.height, im.width, cx, cy)!!
        val rings = listOf(51.0 to 59.0, 40.0 to 48.0, 29.0 to 37.0)
        for ((ring, r) in rings.withIndex()) {
          val m = (r.first + r.second) / 2
          for (k in 0 until 24) {
            val mu = k * 15 + 7.5
            val pts = listOf(m to mu, m to mu - 3, m to mu + 3, m - 1 to mu, m + 1 to mu)
            val farOut =
                pts.any { (rr, a) ->
                  val x = cx + ppm * rr * sin(Math.toRadians(a))
                  val y = cy - ppm * rr * cos(Math.toRadians(a))
                  x < -2 || x > im.width + 1 || y < -2 || y > im.height + 1
                }
            if (farOut) {
              assertNull("$side $cut ring $ring cell $k", cells[ring * 24 + k])
              checked++
            }
          }
        }
      }
    }
    assertTrue(foundAny > 0)
    assertTrue(checked > 0)
  }

  @Test
  fun degenerateInputsRejectWithoutRaising() {
    val xs = DoubleArray(70) { 1.0 } // all edges at one point: singular normal matrix
    val ys = DoubleArray(70) { 2.0 }
    assertNull(RingDetector.fitConic(xs, ys, 70))
    assertNull(RingDetector.Frame.fromConic(null, 0.0, 0.0))
    val detector = RingDetector()
    val grey = ByteArray(120 * 160) { 128.toByte() }
    assertEquals(emptyList<RingDetection>(), detector.detect(grey, 160, 120))
    assertEquals(emptyList<RingDetection>(), detector.detect(ByteArray(120 * 160), 160, 120))
  }

  @Test
  fun nonFiniteSamplesAreOffImage() {
    val nan = Double.NaN
    val inf = Double.POSITIVE_INFINITY
    assertEquals(6, RingDetector.nearestIndex(1.0, 1.0, 5, 4))
    for ((x, y) in listOf(nan to 1.0, 1.0 to nan, inf to 1.0, -inf to 1.0, 1.0 to inf)) {
      assertEquals("nearest ($x, $y)", -1, RingDetector.nearestIndex(x, y, 5, 4))
      assertTrue("inside ($x, $y)", !RingDetector.inside(x, y, 5, 4))
    }
    assertEquals(-1, RingDetector.nearestIndex(4.6, 1.0, 5, 4))
    assertTrue(RingDetector.inside(0.0, 3.0, 5, 4) && RingDetector.inside(4.0, 0.0, 5, 4))
    assertTrue(!RingDetector.inside(4.01, 0.0, 5, 4))
  }

  @Test
  fun blobOrderIsRasterOrder() {
    val w = 60
    val img = ByteArray(w * 60) { 200.toByte() }
    for (y in 40 until 50) for (x in 5 until 15) img[y * w + x] = 0 // lower blob, left
    for (y in 5 until 15) for (x in 40 until 50) img[y * w + x] = 0 // upper blob, right: first
    val order = RingDetector().dotCandidates(img, w, 60, w, 15)
    assertEquals(order.map { it.first }.sorted(), order.map { it.first })
    assertTrue(order[0].cy < 30)
  }

  @Test
  fun rowStrideIsHonoured() {
    val e = manifest.single { it.name == "two_markers" }
    val stride = e.image.width + 13
    val padded = ByteArray(stride * e.image.height) { 77 }
    for (y in 0 until e.image.height) {
      System.arraycopy(e.image.gray, y * e.image.width, padded, y * stride, e.image.width)
    }
    assertEquals(
        detections.getValue("two_markers"),
        RingDetector().detect(padded, e.image.width, e.image.height, stride),
    )
  }

  private fun crop(img: Image, side: String, cut: Int): Image {
    val (x0, y0, x1, y1) =
        when (side) {
          "left" -> listOf(cut, 0, img.width, img.height)
          "right" -> listOf(0, 0, img.width - cut, img.height)
          "top" -> listOf(0, cut - 160, img.width, img.height)
          else -> listOf(0, 0, img.width, img.height - cut + 160)
        }
    val w = x1 - x0
    val out = ByteArray(w * (y1 - y0))
    for (y in y0 until y1) System.arraycopy(img.gray, y * img.width + x0, out, (y - y0) * w, w)
    return Image(out, w, y1 - y0)
  }

  companion object {
    private val dir = File("../../ring-marker/testset")

    /**
     * Reads an 8-bit grey PNG with javax.imageio.ImageIO. Unit tests compile against android.jar,
     * which lacks javax.imageio and java.awt, so they are reached reflectively (they exist at run
     * time on the JVM).
     */
    private fun load(file: File): Image {
      val image = Class.forName("java.awt.image.BufferedImage")
      val rasterType = Class.forName("java.awt.image.Raster")
      val io = Class.forName("javax.imageio.ImageIO")
      val bi = io.getMethod("read", File::class.java).invoke(null, file)!!
      val width = image.getMethod("getWidth").invoke(bi) as Int
      val height = image.getMethod("getHeight").invoke(bi) as Int
      val raster = image.getMethod("getRaster").invoke(bi)!!
      require(rasterType.getMethod("getNumBands").invoke(raster) == 1) { "$file is not grey" }
      val px =
          rasterType
              .getMethod(
                  "getPixels",
                  Int::class.java,
                  Int::class.java,
                  Int::class.java,
                  Int::class.java,
                  IntArray::class.java,
              )
              .invoke(raster, 0, 0, width, height, null) as IntArray
      return Image(ByteArray(px.size) { px[it].toByte() }, width, height)
    }

    private val manifest: List<Entry> by lazy {
      val root = Json.parseToJsonElement(File(dir, "manifest.json").readText()).jsonArray
      assertEquals(38, root.size)
      root.map { v ->
        val o = v.jsonObject
        Entry(
            o["name"]!!.jsonPrimitive.content,
            o["case"]!!.jsonPrimitive.content,
            o["expect"]!!.jsonPrimitive.content == "none",
            o["markers"]!!.jsonArray.map { it.jsonObject },
            load(File(dir, o["file"]!!.jsonPrimitive.content)),
        )
      }
    }

    private val detections: Map<String, List<RingDetection>> by lazy {
      val d = RingDetector()
      manifest.associate { it.name to d.detect(it.image.gray, it.image.width, it.image.height) }
    }
  }
}
